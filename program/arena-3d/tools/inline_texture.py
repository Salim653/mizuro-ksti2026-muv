#!/usr/bin/env python3
"""Regenerate track_floor_data.js from track_floor.jpg.

The texture has to be inlined because Chrome gives every file:// document its own opaque
origin: loading track_floor.jpg from a double-clicked page is blocked outright
(net::ERR_FAILED), which silently removes the map overlay from the panel. A data: URL is not
a sub-resource request, so it loads everywhere and does not taint the capture canvas.

Run from anywhere:  python arena-3d/tools/inline_texture.py
"""
import base64, os, sys

here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(here, 'track_floor.jpg')
if not os.path.exists(src):
    sys.exit('missing %s - re-run extract_track.py first' % src)

raw = open(src, 'rb').read()
b64 = base64.b64encode(raw).decode('ascii')
js = ("""/* The map texture inlined as a data: URL. Chrome gives every file:// document its own
   opaque origin, so loading track_floor.jpg from a double-clicked page is blocked outright
   (net::ERR_FAILED) and the overlay silently disappears from the panel. A data: URL is not a
   sub-resource request, so it loads everywhere and does not taint the capture canvas.
   Generated by tools/inline_texture.py - regenerate that way, do not hand-edit. */
window.TRACK_FLOOR_DATA = 'data:image/jpeg;base64,%s';
""" % b64)
dst = os.path.join(here, 'track_floor_data.js')
open(dst, 'w', encoding='utf-8').write(js)
print('%s: %d -> %d bytes' % (os.path.basename(dst), len(raw), os.path.getsize(dst)))
