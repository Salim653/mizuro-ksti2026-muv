'',
'    ds = Dataset(args.zip_path)',
'    ids = ds.meta["class_ids"]',
'    sim = ds.meta["sim"]',
'    car = ds.meta["car"]',
'    # accept either spelling so an archive from the older build still loads; a KeyError here',
'    # would otherwise look like a bug in the detector rather than a schema drift',
'    if "wheelbase_m" in car:',
'        wb = float(car["wheelbase_m"])',
'    elif "wb" in car:',
'        wb = float(car["wb"])',
'    else:',
'        sys.exit("dataset.json has no car.wheelbase_m - keys present: %s" %',
'                 ", ".join(sorted(car)))',
'    x_ref = anchor_x(ds.anchor, wb)',
'    try:',
'        lane = Lane(ds.z)',
'    except KeyError:',
'        lane = None',
'        print("note: this archive has no track/track_data.json, so the geometry-matched "',
'              "comparison is unavailable and only the axle-truth numbers will print.\\n")',
'    height = ds.mount["height_m"]',
'    pitch = ds.mount["pitch_deg"]',
'    width = float(ds.meta.get("track", {}).get("nominal_width_m", 0.5))',
'',
'    print("dataset   : " + args.zip_path)',
'    print("frames    : %d   %dx%d   hfov %.0f deg" %',
'          (ds.n, ds.K["w"], ds.K["h"], ds.K["hfov"]))',
'    print("camera    : %.3f m high, %.0f deg down, anchor %s axle (x_ref %+0.3f m)" %',
