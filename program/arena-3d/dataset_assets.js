'        # from the car, hence the flip in the raw pair.',
'        off_true = float(row["lane_offset_m"])',
'        he_true = float(row["heading_err_deg"])',
'        if lane is not None:',
'            t_lat, t_head = lane.at(float(row["x_m"]), float(row["z_m"]),',
'                                    float(row["yaw_rad"]), lm["x_eval_m"])',
'            lat_geo.append(lm["lane_left_of_car_m"] - t_lat)',
'            head_geo.append(np.rad2deg(lm["heading_err_rad"]) - t_head)',
'        lat_raw.append(lm["lane_left_of_car_m"] + off_true)',
'        head_raw.append(np.rad2deg(lm["heading_err_rad"]) - he_true)',
'',
'    print("frames scored : %d   (unrecovered: %d)" % (len(rec), skipped))',
'    if not lat_raw:',
