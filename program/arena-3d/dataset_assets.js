'        lm = lane_model(xs, yl, yr, x_ref)',
'        if lm is None:',
'            skipped += 1',
'            continue',
'        v_true = float(row["speed_mps"])',
'        cmd = stanley(lm["heading_err_rad"], lm["lane_left_of_car_m"], v_true)',
'        tgt = speed_target(lm["curvature"], float(sim["alat_mps2"]),',
'                           float(sim["vmax_mps"]))',
'        rec.append((int(row["frame"]), lm, cmd, tgt))',
'        # Two comparisons, kept apart on purpose.',
'        #   *_geo : against the painted centreline evaluated at the SAME station the fit used',
'        #           (track/track_data.json + ego pose). Detector error and nothing else.',
'        #   *_raw : against the app truth quoted at the axle anchor. A 0.16 m mount cannot see',
'        #           the lane beside the car, so on a map with 0.5-2 m corners the station gap',
'        #           dwarfs the detector error - that gap is the number to design around.',
