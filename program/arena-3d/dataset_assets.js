'# ------------------------------------------------------------------ archive',
'class Lane:',
'    """Exact ground truth from the exported centreline (track/track_data.json), evaluated at',
'       ANY forward station. Needed because a low mount cannot see the lane beside the car:',
'       the fit lands 0.5-0.8 m ahead, and on a corner of 1 m radius the lane turns ~40 deg',
