'          (ds.meta["mode"], ds.meta["sim"]["route"], args.detector))',
'',
'    lat_geo, head_geo, lat_raw, head_raw, rec, skipped = [], [], [], [], [], 0',
'    for i in range(ds.n):',
'        if args.limit and len(rec) >= args.limit:',
'            break',
'        row = ds.rows[i]',
'        if row["state"] != "running":',
'            continue',
'        mask = (edges_from_label(ds.label(i), ids) if args.detector == "label"',
'                else edges_from_rgb(ds.rgb(i)))',
